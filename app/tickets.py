from __future__ import annotations

from typing import Any

SUMMARY_LIMIT = 250


def _paragraph(text: str) -> dict[str, Any]:
    return {"type": "paragraph", "content": [{"type": "text", "text": text}]}


def _heading(text: str, level: int = 3) -> dict[str, Any]:
    return {"type": "heading", "attrs": {"level": level}, "content": [{"type": "text", "text": text}]}


def _bullet(text: str) -> dict[str, Any]:
    return {"type": "listItem", "content": [_paragraph(text)]}


def build_adf_description(finding: dict[str, Any], repository: str, analysis_id: str) -> dict[str, Any]:
    details = [
        f"Rule: {finding['rule_id']} ({finding['title']})",
        f"Severity: {finding['severity']}",
        f"Source file: {finding['file']}",
        f"Line number: {finding['line']}",
        f"Repository: {repository}",
        f"RepoMind analysis: {analysis_id}",
        "Confidence: heuristic static-analysis match",
    ]
    return {
        "type": "doc",
        "version": 1,
        "content": [
            _heading("Finding"),
            _paragraph(finding["explanation"]),
            _paragraph("This is a heuristic review suggestion. It is not a confirmed defect or vulnerability until "
                       "a developer verifies it."),
            _heading("Details"),
            {"type": "bulletList", "content": [_bullet(item) for item in details]},
            _heading("Evidence"),
            {"type": "codeBlock", "attrs": {"language": "python"},
             "content": [{"type": "text", "text": finding["evidence"] or "(no evidence line)"}]},
            _heading("Suggested remediation"),
            _paragraph(finding["remediation"]),
        ],
    }


def build_plain_description(finding: dict[str, Any], repository: str, analysis_id: str) -> str:
    return (
        f"Finding: {finding['explanation']}\n"
        f"Rule: {finding['rule_id']} ({finding['title']})\n"
        f"Severity: {finding['severity']}\n"
        f"Source file: {finding['file']}\n"
        f"Line number: {finding['line']}\n"
        f"Repository: {repository}\n"
        f"RepoMind analysis: {analysis_id}\n"
        f"Evidence: {finding['evidence']}\n\n"
        f"Suggested remediation: {finding['remediation']}\n\n"
        "This was generated by a heuristic and is not proof of a defect."
    )


def make_ticket_draft(finding: dict[str, Any], repository: str = "unknown repository",
                      analysis_id: str = "unknown", project_key: str = "", issue_type: str = "Task") -> dict[str, Any]:
    severity = finding.get("severity", "info")
    summary = f"[RepoMind] {finding.get('rule_id', 'review')}: {finding.get('title', 'Code review item')} in " \
              f"{finding.get('file', 'unknown file')}:{finding.get('line', '?')}"
    warnings = []
    if severity == "info":
        warnings.append("Informational finding. Consider whether a ticket is needed before creating one.")
    return {
        "project": project_key,
        "issue_type": issue_type,
        "summary": summary[:SUMMARY_LIMIT],
        "labels": ["repomind-ai", "code-review", f"severity-{severity}", f"rule-{str(finding.get('rule_id', 'review')).lower()}"],
        "description": build_plain_description(finding, repository, analysis_id),
        "description_adf": build_adf_description(finding, repository, analysis_id),
        "finding_id": finding.get("id"),
        "warnings": warnings,
    }
